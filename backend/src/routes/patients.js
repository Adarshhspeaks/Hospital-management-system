const express = require('express');
const db = require('../db');
const { requireAuth, requireRole } = require('../middleware/auth');

const router = express.Router();
const GENDERS = ['Male', 'Female', 'Other'];
const BLOOD_GROUPS = ['A+', 'A-', 'B+', 'B-', 'AB+', 'AB-', 'O+', 'O-'];

router.use(requireAuth);

// Validates and cleans the patient form. Returns { error } or { data }.
function validate(body = {}) {
  const name = String(body.name || '').trim();
  const age = Number(body.age);
  const gender = body.gender;
  const phone = String(body.phone || '').trim();
  const address = String(body.address || '').trim();
  const bloodGroup = body.blood_group || body.bloodGroup || null;

  if (!name) return { error: 'Enter the patient’s full name.' };
  if (!Number.isInteger(age) || age < 0 || age > 120) return { error: 'Age must be a whole number between 0 and 120.' };
  if (!GENDERS.includes(gender)) return { error: 'Choose a gender.' };
  if (!/^[0-9]{10,15}$/.test(phone)) return { error: 'Phone number must be 10 to 15 digits, with no spaces or symbols.' };
  if (bloodGroup && !BLOOD_GROUPS.includes(bloodGroup)) return { error: 'Choose a valid blood group.' };

  return { data: { name, age, gender, phone, address: address || null, bloodGroup } };
}

// GET /api/patients?q=  : search by ID, name or phone (FR-2.3). Without q, returns the latest 50.
router.get('/', requireRole('receptionist', 'doctor', 'admin'), async (req, res) => {
  const q = String(req.query.q || '').trim();
  try {
    if (!q) {
      const { rows } = await db.query('SELECT * FROM patients ORDER BY patient_id DESC LIMIT 50');
      return res.json(rows);
    }
    // "P-0012", "p12" and "12" all mean patient 12
    const idMatch = q.match(/^p?-?0*(\d+)$/i);
    const id = idMatch ? Number(idMatch[1]) : -1;
    const { rows } = await db.query(
      `SELECT * FROM patients
       WHERE name ILIKE $1 OR phone LIKE $1 OR patient_id = $2::int
       ORDER BY patient_id DESC LIMIT 50`,
      [`%${q}%`, id > 2147483647 ? -1 : id]
    );
    res.json(rows);
  } catch (err) {
    console.error(err);
    res.status(500).json({ error: 'Could not search patients.' });
  }
});

// POST /api/patients : register (FR-2.1, FR-2.2: the ID is generated by the database)
router.post('/', requireRole('receptionist'), async (req, res) => {
  const { error, data } = validate(req.body);
  if (error) return res.status(400).json({ error });

  try {
    const { rows } = await db.query(
      `INSERT INTO patients (name, age, gender, phone, address, blood_group)
       VALUES ($1, $2, $3, $4, $5, $6) RETURNING *`,
      [data.name, data.age, data.gender, data.phone, data.address, data.bloodGroup]
    );
    res.status(201).json(rows[0]);
  } catch (err) {
    console.error(err);
    res.status(500).json({ error: 'Could not register the patient.' });
  }
});

// GET /api/patients/:id : details plus visit history (FR-2.5)
router.get('/:id', requireRole('receptionist', 'doctor', 'admin'), async (req, res) => {
  const id = Number(req.params.id);
  if (!Number.isInteger(id)) return res.status(404).json({ error: 'Patient not found.' });

  try {
    const { rows } = await db.query('SELECT * FROM patients WHERE patient_id = $1', [id]);
    if (!rows[0]) return res.status(404).json({ error: 'Patient not found.' });

    const visits = await db.query(
      `SELECT a.appointment_id, a.date, a.time_slot, a.status,
              u.name AS doctor_name, d.specialization, m.diagnosis
       FROM appointments a
       JOIN doctors d ON d.doctor_id = a.doctor_id
       JOIN users u ON u.user_id = d.user_id
       LEFT JOIN medical_records m ON m.appointment_id = a.appointment_id
       WHERE a.patient_id = $1
       ORDER BY a.date DESC, a.time_slot DESC`,
      [id]
    );

    // Diagnoses are medical records: only doctors may see them (FR-5.4)
    const history = visits.rows.map((v) => ({
      ...v,
      diagnosis: req.user.role === 'doctor' ? v.diagnosis : null,
    }));

    res.json({ patient: rows[0], visits: history });
  } catch (err) {
    console.error(err);
    res.status(500).json({ error: 'Could not load the patient.' });
  }
});

// PUT /api/patients/:id : update details (FR-2.4)
router.put('/:id', requireRole('receptionist'), async (req, res) => {
  const id = Number(req.params.id);
  if (!Number.isInteger(id)) return res.status(404).json({ error: 'Patient not found.' });

  const { error, data } = validate(req.body);
  if (error) return res.status(400).json({ error });

  try {
    const { rows } = await db.query(
      `UPDATE patients
       SET name = $1, age = $2, gender = $3, phone = $4, address = $5, blood_group = $6
       WHERE patient_id = $7 RETURNING *`,
      [data.name, data.age, data.gender, data.phone, data.address, data.bloodGroup, id]
    );
    if (!rows[0]) return res.status(404).json({ error: 'Patient not found.' });
    res.json(rows[0]);
  } catch (err) {
    console.error(err);
    res.status(500).json({ error: 'Could not update the patient.' });
  }
});

module.exports = router;
